/**
  * @brief  Инициализирует модуль апсемплинга DSP.
  * @param  factor: Коэффициент апсемплинга (UP_FACTOR_X2, UP_FACTOR_X4). UP_FACTOR_X1
  *                 не должен быть передан в эту функцию.
  * @param  algo_select: Выбор алгоритма апсемплинга (0 для Algo0, 1 для Algo1).
  * @retval None
  */
void DSP_UpsampleInit(UpFactor_t factor, uint8_t algo_select)
{
    const q15_t *pCoeffs = NULL;
    uint32_t numTaps = 0; // Общее количество отводов для текущего фильтра

    // Выбор коэффициентов в зависимости от коэффициента апсемплинга и выбранного алгоритма
    if (algo_select == 0) // Алгоритм 0
    {
        if (factor == UP_FACTOR_X2)
        {
            pCoeffs = fir_coeffs_algo0_x2;
            numTaps = sizeof(fir_coeffs_algo0_x2) / sizeof(q15_t); // Для x4 используем 60 отводов
        }
        else if (factor == UP_FACTOR_X4)
        {
            pCoeffs = fir_coeffs_algo0_x4;
            numTaps = sizeof(fir_coeffs_algo0_x4) / sizeof(q15_t); // Для x4 используем 120 отводов
        }
    }
    else // Алгоритм 1
    {
        if (factor == UP_FACTOR_X2)
        {
            pCoeffs = fir_coeffs_algo1_x2;
            numTaps = MAX_FIR_TAPS_TOTAL; // Для x2 используем 64 отвода
        }
        else if (factor == UP_FACTOR_X4)
        {
            pCoeffs = fir_coeffs_algo1_x4;
            numTaps = sizeof(fir_coeffs_algo1_x4) / sizeof(q15_t); // Для x4 используем 48 отводов
        }
    }

    // Защита от некорректных параметров или отсутствия фильтра
    if (pCoeffs == NULL || numTaps == 0 || factor == UP_FACTOR_X1)
    {
        // Здесь можно добавить обработку ошибки, например, через Error_Handler()
        // или сообщение об ошибке. Для этого примера просто возвращаемся.
        return;
    }

    // Инициализация FIR-интерполятора для Левого канала
    // L - это коэффициент интерполяции (factor)
    // numTaps - общее количество отводов фильтра
    // pCoeffs - указатель на массив коэффициентов
    // pState - указатель на буфер состояния
    // blockSize - количество входных сэмплов, обрабатываемых за один вызов arm_fir_interpolate_q15
    arm_fir_interpolate_init_q15(&fir_instance_L, factor, numTaps, (q15_t *)pCoeffs, fir_state_L, DSP_UPSAMPLE_BLOCK_SIZE);

    // Инициализация FIR-интерполятора для Правого канала
    // Используются те же коэффициенты и параметры, но свой буфер состояния.
    arm_fir_interpolate_init_q15(&fir_instance_R, factor, numTaps, (q15_t *)pCoeffs, fir_state_R, DSP_UPSAMPLE_BLOCK_SIZE);
}

/**
  * @brief  Выполняет апсемплинг блока аудиоданных.
  *         Примечание: in_len_samples - количество СТЕРЕО сэмплов во входном буфере.
  * @param  in_buffer: Указатель на входной буфер 16-битных стерео сэмплов (Q15).
  * @param  in_len_samples: Количество стерео сэмплов во входном буфере (соответствует blockSize для CMSIS-DSP).
  * @param  out_buffer: Указатель на выходной буфер для 16-битных стерео сэмплов после апсемплинга (Q15).
  * @retval None
  */
void DSP_UpsampleBlock(const int16_t *in_buffer, uint32_t in_len_samples,
                       int16_t *out_buffer)
{
    uint32_t i;

    // 1. Де-интерливинг стерео входных данных в отдельные моно буферы (q15_t)
    // in_buffer содержит [L1, R1, L2, R2, ...], каждый L/R - int16_t
    // temp_mono_in_L будет [L1, L2, ...], temp_mono_in_R будет [R1, R2, ...]
    for (i = 0; i < in_len_samples; i++)
    {
        temp_mono_in_L[i] = in_buffer[2 * i];     // Левый канал
        temp_mono_in_R[i] = in_buffer[2 * i + 1]; // Правый канал
    }

    // 2. Выполнение FIR-интерполяции для каждого моно канала
    // numSamples для arm_fir_interpolate_q15 - это количество входных сэмплов в блоке (для одного канала).
    // Оно совпадает с in_len_samples (количество стерео-сэмплов во входном блоке).
    arm_fir_interpolate_q15(&fir_instance_L, temp_mono_in_L, temp_mono_out_L, in_len_samples);
    arm_fir_interpolate_q15(&fir_instance_R, temp_mono_in_R, temp_mono_out_R, in_len_samples);

    // 3. Ре-интерливинг моно выходных данных в стерео выходной буфер (int16_t)
    // output_len_samples_mono - количество моно-сэмплов на канал после интерполяции.
    // Это in_len_samples * factor.
    uint32_t out_len_samples_mono = in_len_samples * fir_instance_L.L; // fir_instance_L.L хранит коэффициент интерполяции
    for (i = 0; i < out_len_samples_mono; i++)
    {
        out_buffer[2 * i]     = temp_mono_out_L[i]; // Левый канал
        out_buffer[2 * i + 1] = temp_mono_out_R[i]; // Правый канал
    }
}
