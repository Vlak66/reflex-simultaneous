//***************************************************************************
// SPDIF_RX.h
//
// Заголовочный файл для имплементации приемника S/PDIF
//***************************************************************************

#ifndef SPDIFRX_H_
#define SPDIFRX_H_

#include "stm32f4xx_hal.h"

// Размер буфера приема (в 32-битных словах)
#define RX_BUFFER_SIZE  192

//****************************************************************************
// Перечисление eEtatSPDif
//
// Определяет текущее состояние приемника S/PDIF:
// - SPDIF_STOP: Остановлен (ожидание команды на остановку)
// - SPDIF_INACTIVE: Неактивный (ожидание команды на запуск)
// - SPDIF_INIT: Инициализация (подготовка к работе)
// - SPDIF_SYNCHRO: Синхронизация (поиск сигнала)
// - SPDIF_RUN: Рабочий режим (прием данных)
//****************************************************************************
typedef enum {
    SPDIF_STOP,       // Остановлен
    SPDIF_INACTIVE,   // Неактивный
    SPDIF_INIT,       // Инициализация
    SPDIF_SYNCHRO,    // Синхронизация
    SPDIF_RUN         // Работа
} eEtatSPDif;


// Режим работы устройства
typedef enum {
    USB_MODE,         // Режим USB
    SPDIF_MODE        // Режим SPDIF
} DeviceMode;

// Состояние буфера
typedef enum {
    EmptyBuffer,         // Пустой буфер
    FirstFilled,         // Заполнен первый буфер
    SecondFilled         // Заполнен второй буфер
} BufferState;

//****************************************************************************
// Структура SPDIF_RX
//
// Управление приемом потока S/PDIF. Содержит:
// - Указатели на дескрипторы HAL для S/PDIF и таймера
// - Переменные состояния для синхронизации и определения частоты дискретизации
// - Двойной буфер для приема данных через DMA
// - Счетчик обратных вызовов (для отладки)
//****************************************************************************
typedef struct {
    // Дескрипторы HAL
    SPDIFRX_HandleTypeDef* phSPDIFRX; // Указатель на дескриптор S/PDIF
    TIM_HandleTypeDef* phTIM;         // Указатель на дескриптор таймера
    
    // Переменные состояния
    eEtatSPDif EtatSPDif;             // Текущее состояние модуля
    uint32_t Freq_SPDiff_Clk;         // Частота тактового сигнала S/PDIF
    uint32_t SPDiff_SampleRate;       // Текущая частота дискретизации
    
    // Двойной буфер для приема данных S/PDIF
    // Используется для организации DMA-передачи (размер буфера * 2)
    int32_t Buffer[RX_BUFFER_SIZE * 2] __attribute__((aligned(4)));
    
    // Счетчик вызовов callback-функций (для отладки)
    uint64_t CtCallBack;
} SPDIF_RX;

//****************************************************************************
// Объявления функций
//****************************************************************************

// Инициализация всего модуля S/PDIF
void InitSPDIF(void);

// Основные операции
void SPDIF_RX_StartReceive();  // Запуск приема данных
void SPDIF_RX_StopReceive();   // Остановка приема данных

// Методы получения информации
uint32_t SPDIF_RX_GetSampleRate();  // Получить текущую частоту дискретизации
eEtatSPDif SPDIF_RX_GetState();     // Получить текущее состояние модуля

void SetMode(DeviceMode mode);      // Установка режима устройства
DeviceMode getMode();               // Получение режима устройства

void SAITransferCompleteHandler(void); //Обработчик завершения прерывания

#endif // SPDIFRX_H_